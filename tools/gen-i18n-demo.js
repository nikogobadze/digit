/* ==================================================================
   gen-i18n-demo.js — regenerates the demo-content block inside
   public/i18n.js from scripts/demo-content.json.

   Seeded task titles, descriptions and review comments are rendered like any
   other text, so without dictionary entries the Georgian dashboard shows
   English task copy. Generating the block keeps the dictionary and the seed
   from drifting apart: edit demo-content.json, then re-run this.

       node tools/gen-i18n-demo.js

   Keys and values are emitted with JSON.stringify, so quotes and apostrophes
   are escaped correctly without this file having to hand-roll escaping.
================================================================== */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const content = require(path.join(ROOT, 'scripts', 'demo-content.json'));
const target = path.join(ROOT, 'public', 'i18n.js');

const START = '  /* ==== demo content: generated by tools/gen-i18n-demo.js, do not edit by hand ==== */';
const END = '  /* ==== end demo content ==== */';

const q = (s) => JSON.stringify(s);

function entry(en, ka) {
  const key = '  ' + q(en) + ':';
  const val = q(ka);
  // Wrap rather than let long Georgian values run far off the right edge.
  return (key.length + val.length + 1 > 100) ? key + '\n    ' + val + ',' : key + ' ' + val + ',';
}

const lines = [START];

lines.push('  /* seeded task titles */');
for (const t of content.tasks) lines.push(entry(t.en, t.ka));

lines.push('');
lines.push('  /* seeded task descriptions */');
for (const t of content.tasks) lines.push(entry(t.d_en, t.d_ka));

lines.push('');
lines.push('  /* seeded review comments */');
for (const band of ['high', 'mid', 'low']) {
  for (const c of content.comments[band]) lines.push(entry(c.en, c.ka));
}

lines.push(END);
const block = lines.join('\n');

let src = fs.readFileSync(target, 'utf8');
const s = src.indexOf(START);
const e = src.indexOf(END);

if (s !== -1 && e !== -1) {
  src = src.slice(0, s) + block + src.slice(e + END.length);
} else {
  // First run: insert just before the closing brace of I18N_KA.
  const anchor = src.indexOf('\nconst I18N_KA = {');
  if (anchor === -1) throw new Error('could not find I18N_KA in ' + target);
  const close = src.indexOf('\n};', anchor);
  if (close === -1) throw new Error('could not find the end of I18N_KA');
  src = src.slice(0, close + 1) + '\n' + block + '\n' + src.slice(close + 1);
}

fs.writeFileSync(target, src);

const n = content.tasks.length * 2 + ['high', 'mid', 'low']
  .reduce((a, b) => a + content.comments[b].length, 0);
console.log('wrote ' + n + ' demo entries into public/i18n.js');
